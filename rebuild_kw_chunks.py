_STEM_CLEAN_RE = re.compile(r'\s*\(\d{3}USR-[^)]*\)\s*|\s*_formatted(?:\(\d+\))?$|\(\d+\)$')
_PLAN_CODE_RE  = re.compile(r'\b[A-Z]{1,3}\d{3,}-\d+-\d+[A-Z]?\b')

def clean_stem(stem: str) -> str:
    return _STEM_CLEAN_RE.sub('', stem).strip()

def clean_text(text: str) -> str:
    return _PLAN_CODE_RE.sub('', text)

def extract_window(text: str, terms: list[str], window: int = 350) -> str | None:
    """Return a text window centered on the first matched term."""
    for t in terms:
        idx = text.find(t)
        if idx >= 0:
            start = max(0, idx - 150)
            end = min(len(text), start + window)
            return text[start:end].strip()
    return None

def get_related(kw: str) -> list[str]:
    if kw in KEYWORD_RELATED:
        terms = list(KEYWORD_RELATED[kw])
        if kw not in terms:
            terms.insert(0, kw)
        return terms
    # fallback: 字串本身 + 2/3-char substrings
    if len(kw) <= 3:
        return [kw]
    terms = [kw]
    for n in (2, 3):
        for i in range(len(kw) - n + 1):
            t = kw[i:i+n]
            if t not in terms:
                terms.append(t)
    return terms

def main():
    print('載入 FAISS vectorstore...')
    emb = VoyageAIEmbeddings(voyage_api_key=os.environ['VOYAGE_API_KEY'], model='voyage-4-large')
    vs  = FAISS.load_local(str(INDEX_DIR), emb, allow_dangerous_deserialization=True)
    all_docs = list(vs.docstore._dict.values())
    print(f'共 {len(all_docs)} 個 chunk')

    # 全部 keyword
    all_kws = sorted({kw for kws in USR_TOPIC_KEYWORDS.values() for kw in kws})
    print(f'共 {len(all_kws)} 個 keyword')

    # 預先建立每個 keyword 的相關詞集合
    kw_terms: dict[str, list[str]] = {kw: get_related(kw) for kw in all_kws}

    # keyword → {plan → [chunk_text, ...]}（最多 3 個）
    result: dict[str, dict[str, list[str]]] = {kw: defaultdict(list) for kw in all_kws}

    t0 = time.perf_counter()
    skip_re = re.compile(r'qa_custom')
    school_re = re.compile(r'大學|學院|科大|科技大')

    for i, doc in enumerate(all_docs):
        src = doc.metadata.get('source', '')
        if skip_re.search(src) or '114md' not in src:
            continue
        text = clean_text(doc.page_content)
        # 名單型或課程表格跳過
        if text.count('姓名：') >= 2:
            continue
        if text.count('課程名稱') + text.count('修課人次') >= 2:
            continue

        # 取計畫名
        stem  = clean_stem(Path(src).stem)
        parts = stem.split('_', 1)
        if len(parts) < 2:
            continue
        school = parts[0]
        if not school_re.search(school):
            continue
        plan = f"{school}：{parts[1]}"
        if not text.strip():
            continue

        # 對每個 keyword 比對，chunk 取命中字眼周圍的 window
        for kw in all_kws:
            terms = kw_terms[kw]
            window = extract_window(text, terms)
            if window is not None:
                chunks = result[kw][plan]
                if len(chunks) < 3 and window not in chunks:
                    chunks.append(window)

        if (i + 1) % 500 == 0:
            print(f'  [{i+1}/{len(all_docs)}] {round(time.perf_counter()-t0)}s')

    print(f'掃描完成，耗時 {round(time.perf_counter()-t0)}s')

    # 組裝輸出格式
    out_114: dict[str, list[dict]] = {}
    for kw in all_kws:
        entries = []
        for plan, chunks in result[kw].items():
            school = plan.split('：', 1)[0]
            for t in chunks:
                entries.append({'school': school, 'plan': plan, 'text': t, 'hits': 1})
        if entries:
            out_114[kw] = entries

    # 載入現有檔案保留其他 key（如 parent keys 手動加的）
    existing = {}
    if OUTPUT_PATH.exists():
        try:
            existing = json.loads(OUTPUT_PATH.read_text(encoding='utf-8'))
        except Exception:
            pass
    existing['114'] = out_114

    OUTPUT_PATH.write_text(json.dumps(existing, ensure_ascii=False, indent=2), encoding='utf-8')

    total = sum(len(v) for v in out_114.values())
    print(f'\n完成：{len(out_114)} 個 keyword，{total} entries')
    print(f'輸出至 {OUTPUT_PATH}')

    # 簡單統計
    for kw in ['原住民族文化', '原住民族關懷', '食農教育', '長照', '高齡照護']:
        n = len(out_114.get(kw, []))
        plans = len({e["plan"] for e in out_114.get(kw, [])})
        print(f'  {kw}: {n} entries, {plans} 件計畫')

if __name__ == '__main__':
    main()
