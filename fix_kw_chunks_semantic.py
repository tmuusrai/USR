def main() -> None:
    print(f"Loading {INPUT_FILE} …")
    with INPUT_FILE.open("r", encoding="utf-8") as fh:
        data = json.load(fh)

    year_data: dict = data.get("114", {})
    if not year_data:
        print("ERROR: key '114' not found in JSON.")
        return

    removal_log: list[tuple[str, int, int]] = []  # (keyword, before, after)
    total_before = 0
    total_after = 0

    for keyword, entries in year_data.items():
        before = len(entries)
        total_before += before

        # Parent keys are never filtered
        if keyword in PARENT_KEYS:
            total_after += before
            continue

        related_terms = get_related_terms(keyword)

        kept: list[dict] = []
        for entry in entries:
            chunk_text: str = entry.get("text", "")
            if is_relevant(chunk_text, keyword, related_terms):
                kept.append(entry)

        after = len(kept)
        total_after += after

        if after < before:
            year_data[keyword] = kept
            removal_log.append((keyword, before, after))

    # ---------- Print summary ----------
    print("\n" + "=" * 60)
    print(f"{'KEYWORD':<30}  {'BEFORE':>6}  {'AFTER':>6}  {'REMOVED':>7}")
    print("=" * 60)
    removal_log.sort(key=lambda x: x[1] - x[2], reverse=True)  # sort by most removed
    for kw, before, after in removal_log:
        removed = before - after
        print(f"{kw:<30}  {before:>6}  {after:>6}  {removed:>7}")
    print("-" * 60)
    total_removed = total_before - total_after
    print(f"{'TOTAL':<30}  {total_before:>6}  {total_after:>6}  {total_removed:>7}")
    print(f"\nKeywords with removals : {len(removal_log)}")
    print(f"Keywords unchanged     : {len(year_data) - len(removal_log)}")

    # ---------- Write back ----------
    print(f"\nWriting result back to {INPUT_FILE} …")
    with INPUT_FILE.open("w", encoding="utf-8") as fh:
        json.dump(data, fh, ensure_ascii=False, indent=2)
    print("Done.")


if __name__ == "__main__":
    main()
