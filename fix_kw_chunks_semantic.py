# ---------------------------------------------------------------------------
# Helper: build related terms for a keyword not in the mapping
# ---------------------------------------------------------------------------

def _ngrams(text: str, n: int) -> list[str]:
    """Return all n-grams of a string."""
    return [text[i:i + n] for i in range(len(text) - n + 1)]


def get_related_terms(keyword: str) -> list[str]:
    """
    Return the related term list for *keyword*.

    Priority:
      1. Explicit mapping in KEYWORD_RELATED
      2. If keyword is short (≤3 chars), use the keyword itself
      3. Fallback: all 2-char and 3-char substrings of the keyword
    """
    if keyword in KEYWORD_RELATED:
        terms = list(KEYWORD_RELATED[keyword])
        # Always include the exact keyword itself
        if keyword not in terms:
            terms.insert(0, keyword)
        return terms

    if len(keyword) <= 3:
        return [keyword]

    # Fallback: 2-char + 3-char substrings
    terms = _ngrams(keyword, 2) + _ngrams(keyword, 3)
    # Deduplicate while preserving order
    seen: set[str] = set()
    unique: list[str] = []
    for t in terms:
        if t not in seen:
            seen.add(t)
            unique.append(t)
    return unique


# ---------------------------------------------------------------------------
# Core filtering logic
# ---------------------------------------------------------------------------

def is_relevant(chunk_text: str, keyword: str, related_terms: list[str]) -> bool:
    """
    Return True if the chunk is relevant to the keyword.

    Rules (in priority order):
      1. Always keep if the full keyword appears in the text.
      2. Keep if ANY related term appears in the text.
      3. Otherwise drop.
    """
    if keyword in chunk_text:
        return True
    return any(term in chunk_text for term in related_terms)


