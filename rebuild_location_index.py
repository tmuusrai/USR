def parse_county(text: str) -> str:
    """從文字中抽取縣市短名，找不到回傳空字串。"""
    if not text:
        return ""
    for pat, county in _COUNTY_PATTERNS:
        if pat.search(text):
            return county
    # 嘗試鄉鎮地名查表
    for town, county in _TOWN_TO_COUNTY.items():
        if town in text:
            return county
    return ""


