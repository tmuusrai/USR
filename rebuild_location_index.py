ws = wb['國內實踐場域總資料庫']
rows = list(ws.iter_rows(values_only=True))
h = {v: i for i, v in enumerate(rows[0]) if v}

# plan_key → list of (location, region, dedup_set)
plan_locs: dict[str, list[dict]] = defaultdict(list)
plan_region: dict[str, str] = {}
seen: dict[str, set] = defaultdict(set)

for r in rows[1:]:
    school = r[h['學校名稱']]
    plan   = r[h['計畫名稱']]
    loc    = r[h['國內實踐場域（學校/機構）']]
    region = r[h['地區']]

    if not school or not plan:
        continue

    key = f"{school}：{plan}"
    if region:
        plan_region[key] = str(region).strip()

    if not loc:
        continue
    loc = str(loc).strip()
    if loc in seen[key]:
        continue
    seen[key].add(loc)

    # 從場域名稱直接解析縣市
    county = parse_county(loc)
    entry: dict = {"location": loc}
    if county:
        entry["county"] = county
    plan_locs[key].append(entry)

print(f"讀取完成：{len(plan_locs)} 件計畫，共 {sum(len(v) for v in plan_locs.values())} 個場域")

# 第二輪：對沒有縣市的計畫，嘗試從計畫名稱補充縣市
for key, fields in plan_locs.items():
    has_county = any(f.get("county") for f in fields)
    if not has_county:
        plan_county = parse_county(key)
        if plan_county:
            if fields:
                for f in fields:
                    if not f.get("county"):
                        f["county"] = plan_county
            else:
                # 無場域記錄時加一個虛擬佔位（只帶縣市）
                fields.append({"county": plan_county, "location": ""})
            print(f"  [計畫名補縣市] {key} → {plan_county}")

# 統計
with_county = sum(1 for fields in plan_locs.values() if any(f.get("county") for f in fields))
without_county = [(k, plan_region.get(k, "?"), [f["location"] for f in v[:3]])
                  for k, v in plan_locs.items()
                  if not any(f.get("county") for f in v)]
print(f"\n有縣市：{with_county}/{len(plan_locs)}")
if without_county:
    print(f"無縣市 ({len(without_county)} 件)：")
    for k, reg, locs in without_county:
        print(f"  [{reg}] {k}")
        print(f"    locs: {locs}")

# ── 手動覆蓋：場域名稱無縣市關鍵字，依學校所在地/地區推斷 ──────────────────
_MANUAL_COUNTY: dict[str, str] = {
    # 實踐大學台北校區；中華民國運動神經元疾病病友協會辦公室在台北
    "實踐大學：漸凍病症及相似病徵病友的科技生活設計": "台北",
    # 合作場域（中國醫藥/中臺科技/朝陽科大）均在台中；亞洲大學在台中霧峰
    "亞洲大學：食品安全與健康的守護者": "台中",
    # 正修科技大學在高雄楠梓；地區=高屏澎東
    "正修科技大學：否極泰來–原住民文化資產保存人才培育與在地實踐計畫": "高雄",
    # 暨南大學在南投埔里；「水沙連」為南投日月潭/埔里地區舊稱
    "國立暨南國際大學：水沙連區域產業永續發展計畫：地方創生 x 借鏡日本 x 連結泰國": "南投",
}

for key, county in _MANUAL_COUNTY.items():
    if key in plan_locs:
        for f in plan_locs[key]:
            if not f.get("county"):
                f["county"] = county
        print(f"  [手動補縣市] {key} → {county}")
    else:
        # 計畫不在 Excel（如純海外計畫），直接在後段寫入 location_index
        pass

# ── 更新 location_index.json ──────────────────────────────────────────────────
loc_data = json.loads(LOCATION_PATH.read_text(encoding="utf-8"))
plans_114 = loc_data.setdefault("114", {}).setdefault("plans", {})

updated = added = 0
for key, fields in plan_locs.items():
    if key not in plans_114:
        plans_114[key] = {}
        added += 1
    else:
        updated += 1
    # 只更新 fields，保留 overseas_fields / overseas_countries
    plans_114[key]["fields"] = fields

# 手動補縣市（不在 Excel 的計畫，如純海外計畫）
for key, county in _MANUAL_COUNTY.items():
    if key not in plan_locs and key in plans_114:
        if not plans_114[key].get("fields"):
            plans_114[key]["fields"] = [{"county": county, "location": ""}]
        else:
            for f in plans_114[key]["fields"]:
                if not f.get("county"):
                    f["county"] = county
        print(f"  [手動補縣市(直接)] {key} → {county}")

LOCATION_PATH.write_text(
    json.dumps(loc_data, ensure_ascii=False, indent=2),
    encoding="utf-8"
)
print(f"\nlocation_index.json：更新 {updated} 件、新增 {added} 件 → 已存檔")
print("完成！")
